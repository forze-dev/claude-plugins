#!/usr/bin/env node
/**
 * PreToolUse hook of the landing@forze plugin.
 *
 * Acts ONLY in projects created by the plugin — those with
 * `.forze/landing.json` at the root. In any other project the hook does
 * nothing: the plugin is enabled globally and has no right to block writes to
 * someone else's `dist/`.
 *
 * What it blocks (exit 2 + an explanation to the agent on stderr):
 *   1. writing or editing files in `dist/` and `release/` — the build generates
 *      them and overwrites them entirely, so manual edits are always lost work;
 *   2. `npm audit fix --force` — it changes major versions and breaks the pins
 *      (rule 4);
 *   3. `npm install` / `npm i` with no arguments — it may pull versions other
 *      than the lock file; `npm ci` is the way to install;
 *   4. creating a `.env` / `.env.*` file inside `public/` — everything there is
 *      copied into dist/ and served to anyone. Credentials belong at the project
 *      root locally and in `secrets/` above public_html on the hosting.
 *
 * A failure in the hook itself (broken JSON input etc.) does not block work:
 * exit 0. The hook is a safety net, not a point of failure.
 */

import { existsSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';

const MARKER = join('.forze', 'landing.json');

/** The nearest ancestor (or the folder itself) that holds the project marker. */
function projectRoot(start) {
	let dir = resolve(start);
	for (;;) {
		if (existsSync(join(dir, MARKER))) return dir;
		const parent = dirname(dir);
		if (parent === dir) return null;
		dir = parent;
	}
}

function block(message) {
	process.stderr.write(`[landing@forze] ${message}\n`);
	process.exit(2);
}

let input = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => (input += chunk));
process.stdin.on('end', () => {
	let event;
	try {
		event = JSON.parse(input);
	} catch {
		process.exit(0);
	}

	const cwd = event.cwd || process.cwd();
	const tool = event.tool_name;
	const params = event.tool_input || {};

	if (['Write', 'Edit', 'MultiEdit', 'NotebookEdit'].includes(tool)) {
		const raw = params.file_path || params.notebook_path;
		if (!raw) process.exit(0);
		const file = isAbsolute(raw) ? raw : resolve(cwd, raw);
		const root = projectRoot(dirname(file));
		if (!root) process.exit(0);

		const parts = relative(root, file).split(sep);
		const first = parts[0];
		if (first === 'public' && /^\.env(\..*)?$/.test(parts[parts.length - 1]) && parts[parts.length - 1] !== '.env.example') {
			block(
				'A credentials file must never be inside public/: it would be copied into dist/ and served to anyone. ' +
					'Locally keep .env.<domain> at the project root; on the hosting it goes into secrets/ one level above public_html.'
			);
		}
		if (first === 'dist' || first === 'release') {
			block(
				`${first}/ is generated by the build and overwritten entirely — a manual edit will be lost. ` +
					`Change the source instead: src/ (pages, components), public/ (static files), ` +
					`server/htaccess.template (.htaccess), server/form.php (back end), then npm run build.`
			);
		}
		process.exit(0);
	}

	if (tool === 'Bash' || tool === 'PowerShell') {
		const root = projectRoot(cwd);
		if (!root) process.exit(0);
		const command = String(params.command || '');

		if (/\bnpm\s+audit\s+fix\b[^\n;&|]*--force/.test(command)) {
			block(
				'npm audit fix --force changes major versions and breaks the dependency pins (rule 4 in CLAUDE.md). ' +
					'Assess each advisory first (rule 6) and discuss the upgrade with the developer.'
			);
		}

		// `npm install` / `npm i` without a package name reinstalls with the right
		// to change versions. Installing a specific package is not blocked.
		if (/\bnpm\s+(install|i)\s*($|[;&|])/m.test(command)) {
			block('Use `npm ci` to install dependencies in this project — exact versions from the lock file (rule 4).');
		}
	}

	process.exit(0);
});
